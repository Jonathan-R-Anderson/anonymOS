"""The controller verifies the directive before it rewrites anybody's DNS.

This service holds the credentials that rewrite DNS for every gateway in the
network. A document that redirects those, accepted without a signature, is the
most valuable thing in the system to forge — so it is checked, even though the
controller runs beside the origin and is operated by the same person.

The curve maths is hand-written (see backend/directive.py for why), which makes
these tests load-bearing rather than decorative. The signature fixtures are
generated by the GO implementation in storage-client, so three independent
implementations are held to the same bytes.
"""

from __future__ import annotations

import asyncio
import json
import pathlib

import pytest

from backend.directive import (
    canonical,
    is_effective,
    keccak256,
    recover_signer,
    same_address,
    verify_document,
    zone_from,
)

FIXTURES = json.loads(
    (pathlib.Path(__file__).parent / "data" / "directive_signatures.json").read_text()
)
# Private key 1. A published Ethereum vector, so this checks the address
# derivation against the outside world rather than against itself.
KEY_ONE = "0x7e5f4552091a69125d5dfcb7b8c2659029395bdf"


class TestKeccak:
    def test_known_vectors(self):
        assert keccak256(b"").hex() == (
            "c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470")
        assert keccak256(b"abc").hex() == (
            "4e03657aea45a94fc7d47ba826c8d667c0d1e6e33a64a036ec44f58fa12d6c45")

    def test_it_is_not_sha3(self):
        """SHA-3 pads with 0x06 where keccak pads with 0x01. Same structure,
        different function — close enough to look right and never match."""
        import hashlib

        assert keccak256(b"abc") != hashlib.sha3_256(b"abc").digest()


class TestRecovery:
    @pytest.mark.parametrize("name", sorted(FIXTURES))
    def test_go_generated_signatures(self, name):
        case = FIXTURES[name]
        assert same_address(
            recover_signer(case["message"], case["signature"]), case["address"])

    def test_the_published_vector_for_private_key_one(self):
        case = FIXTURES["0000"]
        assert same_address(case["address"], KEY_ONE)
        assert same_address(
            recover_signer(case["message"], case["signature"]), KEY_ONE)

    def test_a_changed_message_recovers_someone_else(self):
        case = FIXTURES["0001"]
        altered = case["message"].replace("syndichan.net", "evil.example")
        assert not same_address(
            recover_signer(altered, case["signature"]), case["address"])

    @pytest.mark.parametrize("signature", [
        "", "0x", "not hex", "0x1234", "0x" + "00" * 66, "0x" + "00" * 65,
    ])
    def test_garbage_is_refused(self, signature):
        assert recover_signer("hello", signature) is None

    def test_a_high_s_signature_is_refused(self):
        """Every signature has a valid low-s twin. Accepting both means two
        distinct signatures over one message, which makes "have I seen this
        directive already?" a question with no reliable answer."""
        n = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
        case = FIXTURES["0000"]
        raw = bytearray.fromhex(case["signature"][2:])
        s = int.from_bytes(raw[32:64], "big")
        raw[32:64] = (n - s).to_bytes(32, "big")
        assert recover_signer(case["message"], "0x" + raw.hex()) is None

    def test_empty_addresses_never_match(self):
        """That is the shape of a controller with no pinned wallet accepting
        whatever arrives."""
        assert not same_address("", "")
        assert not same_address(None, None)
        assert not same_address(KEY_ONE, "")


def _document(sequence=3, domain="syndichan.net", canonical_override=None):
    case = FIXTURES["0001"]
    directive = {
        "kind": "move", "sequence": sequence, "issued_at": 0, "not_before": 0,
        "emergency": False, "origin_domain": domain, "origin_address": "",
        "origin_key": "", "note": "",
    }
    return {
        "directive": directive,
        "canonical": canonical_override if canonical_override is not None
        else canonical(directive),
        "signature": case["signature"],
    }, case["address"]


class TestVerifyDocument:
    def test_a_matching_document_verifies(self):
        document, wallet = _document()
        assert verify_document(document, wallet) is not None

    def test_another_wallet_is_refused(self):
        document, _ = _document()
        assert verify_document(document, KEY_ONE.replace("7e5f", "0000")) is None

    def test_no_pinned_wallet_verifies_nothing(self):
        document, _ = _document()
        for wallet in ("", None, "not-an-address", "0x123"):
            assert verify_document(document, wallet) is None

    def test_text_disagreeing_with_the_fields_is_refused(self):
        """Otherwise one valid signature vouches for values nobody signed."""
        document, wallet = _document(domain="evil.example")
        good, _ = _document(domain="syndichan.net")
        document["canonical"] = good["canonical"]
        assert verify_document(document, wallet) is None

    def test_a_replay_is_refused(self):
        document, wallet = _document(sequence=3)
        assert verify_document(document, wallet, held_sequence=3) is None
        assert verify_document(document, wallet, held_sequence=9) is None
        assert verify_document(document, wallet, held_sequence=2) is not None

    @pytest.mark.parametrize("document", [None, {}, {"directive": "nope"},
                                          {"directive": {}}])
    def test_malformed_documents_return_none_rather_than_raising(self, document):
        """This runs in a scheduled DNS sync. A controller that crashed on a bad
        document would stop maintaining records for every gateway because one
        fetch was malformed."""
        assert verify_document(document, KEY_ONE) is None


class TestZone:
    def test_a_move_changes_the_zone(self):
        assert zone_from({"kind": "move", "origin_domain": "syndichan.net"},
                         "syndichan.org") == "syndichan.net"

    def test_a_freeze_does_not_empty_the_zone(self):
        """Reading a freeze as a move to nowhere would have the controller
        manage an empty zone — deleting every gateway record in the network."""
        for directive in (None, {"kind": "freeze"}, {"kind": "resume"},
                          {"kind": "move", "origin_domain": ""}):
            assert zone_from(directive, "syndichan.org") == "syndichan.org"

    def test_effectiveness_honours_not_before(self):
        directive = {"kind": "move", "not_before": 1000}
        assert not is_effective(directive, 999)
        assert is_effective(directive, 1000)
        assert not is_effective(None, 10**9)


class TestCanonicalMatchesTheOtherImplementations:
    def test_it_reproduces_the_signed_message(self):
        """The message in the fixture was rendered by PYTHON in the backend and
        signed by GO. If this file renders it differently, the controller
        verifies nothing that either of the others produces."""
        case = FIXTURES["0001"]
        directive = {
            "kind": "move", "sequence": 3, "issued_at": 0, "not_before": 0,
            "emergency": False, "origin_domain": "syndichan.net",
            "origin_address": "", "origin_key": "", "note": "",
        }
        assert canonical(directive) == case["message"]


class TestDirectiveTracker:
    """The zone the controller manages, and what must NOT move it."""

    @staticmethod
    def _tracker(monkeypatch, document, wallet, **kwargs):
        import httpx

        from backend.directive_source import DirectiveTracker

        class _Response:
            status_code = 200

            def json(self):
                return document

        class _Client:
            async def get(self, url):
                if document is None:
                    raise httpx.ConnectError("down")
                return _Response()

            async def aclose(self):
                pass

        return DirectiveTracker("syndichan.org", wallet, client=_Client(), **kwargs)

    def test_a_verified_move_changes_the_zone(self, monkeypatch):
        document, wallet = _document()
        tracker = self._tracker(monkeypatch, document, wallet)
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.net"

    def test_an_unverifiable_document_leaves_the_zone_alone(self, monkeypatch):
        # A different wallet from the one that signed. (KEY_ONE would be WRONG
        # here — the fixtures are signed by private key 1, so KEY_ONE is the
        # correct signer and this test would silently assert nothing.)
        document, signer = _document()
        other = "0x" + ("b" * 40)
        assert not same_address(other, signer)
        tracker = self._tracker(monkeypatch, document, other)
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.org"

    def test_a_failed_fetch_leaves_the_zone_alone(self, monkeypatch):
        """A controller that fell back to a default because one request timed
        out would rewrite DNS for every gateway over a transient error."""
        _, wallet = _document()
        tracker = self._tracker(monkeypatch, None, wallet)
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.org"

    def test_no_pinned_wallet_never_moves_the_zone(self, monkeypatch):
        document, _ = _document()
        tracker = self._tracker(monkeypatch, document, "")
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.org"

    def test_a_directive_that_is_not_effective_yet_is_not_applied(self, monkeypatch):
        document, wallet = _document()
        document["directive"]["not_before"] = 5000
        document["canonical"] = canonical(document["directive"])
        # Re-signing is not possible here, so this asserts the ordering instead:
        # an unverifiable document must not move the zone either way.
        tracker = self._tracker(monkeypatch, document, wallet)
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.org"

    def test_it_does_not_poll_on_every_call(self, monkeypatch):
        """Each check is a request to a host that may no longer be ours."""
        document, wallet = _document()
        tracker = self._tracker(monkeypatch, document, wallet, refresh_seconds=600)
        assert asyncio.run(tracker.refresh(now=1000)) == "syndichan.net"
        # A stale, lower-sequence document arriving inside the window must not
        # be consulted at all.
        assert asyncio.run(tracker.refresh(now=1100)) == "syndichan.net"
