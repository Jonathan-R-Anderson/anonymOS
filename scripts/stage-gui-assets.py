#!/usr/bin/env python3
"""Stage generated GUI assets for the guest asset pipeline.

The source tree for boot assets lives under build/assets and is packed later by
scripts/pack-assets.py.  This script keeps G10 assets reproducible: it creates a
small original icon/theme/background set and, when available, vendors the libre
DMZ cursor theme into the generated Epin cursor theme.
"""
from __future__ import annotations

import argparse
import shutil
import struct
import zlib
from pathlib import Path


GENERATED_LICENSE = """Epin generated GUI assets

Files generated by scripts/stage-gui-assets.py are dedicated to the public
domain under CC0-1.0, or may be used under the project license at your option.

Bundled DMZ cursor files, when present, retain their upstream license. See
LICENSE.DMZ-White.txt in the generated icon theme directory.
"""


def write_text(path: Path, data: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8")


def write_png(path: Path, width: int, height: int, variant: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    rows = []
    for y in range(height):
        row = bytearray([0])
        for x in range(width):
            fx = x / max(1, width - 1)
            fy = y / max(1, height - 1)
            if variant == 1:
                r = int(30 + 42 * fx + 16 * fy)
                g = int(44 + 96 * fy)
                b = int(58 + 110 * (1.0 - fx))
            elif variant == 2:
                r = int(38 + 100 * fy)
                g = int(46 + 72 * (1.0 - fx))
                b = int(72 + 90 * fx)
            else:
                r = int(32 + 92 * fx)
                g = int(48 + 84 * (1.0 - abs(fx - fy)))
                b = int(64 + 96 * fy)
            row.extend((r, g, b))
        rows.append(bytes(row))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    data = b"\x89PNG\r\n\x1a\n"
    data += chunk(b"IHDR", ihdr)
    data += chunk(b"IDAT", zlib.compress(b"".join(rows), level=9))
    data += chunk(b"IEND", b"")
    path.write_bytes(data)


