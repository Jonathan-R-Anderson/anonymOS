def stage_icons(root: Path) -> None:
    theme = root / "icons" / "Epin"
    if theme.exists():
        shutil.rmtree(theme)
    (theme / "scalable" / "apps").mkdir(parents=True, exist_ok=True)
    (theme / "scalable" / "places").mkdir(parents=True, exist_ok=True)
    (theme / "scalable" / "mimetypes").mkdir(parents=True, exist_ok=True)
    write_text(theme / "LICENSE.txt", GENERATED_LICENSE)
    write_text(
        theme / "index.theme",
        """[Icon Theme]
Name=Epin
Comment=Generated Epin desktop icon theme
Inherits=hicolor
Directories=scalable/apps,scalable/places,scalable/mimetypes

[scalable/apps]
Size=128
Type=Scalable
MinSize=16
MaxSize=256
Context=Applications

[scalable/places]
Size=128
Type=Scalable
MinSize=16
MaxSize=256
Context=Places

[scalable/mimetypes]
Size=128
Type=Scalable
MinSize=16
MaxSize=256
Context=MimeTypes
""",
    )
    for name in ("terminal", "file-manager", "settings", "system-monitor"):
        write_text(theme / "scalable" / "apps" / f"{name}.svg", svg_icon(name))
    write_text(theme / "scalable" / "places" / "folder.svg", svg_icon("folder"))
    write_text(theme / "scalable" / "mimetypes" / "text-x-generic.svg", svg_icon("text-x-generic"))

    default = root / "icons" / "default"
    if default.exists():
        shutil.rmtree(default)
    write_text(default / "index.theme", "[Icon Theme]\nInherits=Epin\n")
    write_text(default / "cursor.theme", "[Icon Theme]\nInherits=Epin\n")

    # hicolor is the theme every other theme inherits from, and it shipped EMPTY --
    # "Directories=" with nothing behind it.  So when a lookup missed in Epin, the fallback chain
    # ended nowhere, GTK then looked for "image-missing", found nothing there either, and
    # gtkiconhelper.c aborted the process.  Give hicolor the fallback icon GTK requires.
    hicolor = root / "icons" / "hicolor"
    # PNG, not SVG.  librsvg here is a STUB (deps/hyprland-hos/Makefile.deps builds
    # librsvg-stub), so gdk-pixbuf cannot decode an SVG at all -- which is why writing
    # image-missing.svg changed nothing and GTK still aborted with the icon "not present".
    # gdk-pixbuf handles PNG natively, so the fallback has to be a PNG to actually load.
    # Several fixed sizes because GTK picks by requested size; GTK_ICON_SIZE_DIALOG is 48.
    sizes = (16, 22, 24, 32, 48, 64, 128)
    for i, sz in enumerate(sizes):
        write_png(hicolor / f"{sz}x{sz}" / "status" / "image-missing.png", sz, sz, i)
    dirs = ",".join(f"{sz}x{sz}/status" for sz in sizes)
    body = "[Icon Theme]\nName=hicolor\nDirectories=" + dirs + "\n"
    for sz in sizes:
        body += f"\n[{sz}x{sz}/status]\nSize={sz}\nType=Fixed\nContext=Status\n"
    write_text(hicolor / "index.theme", body)


def stage_cursors(root: Path, cursor_src: Path | None, cursor_license: Path | None) -> None:
    icon_theme = root / "icons" / "Epin"
    cursors = icon_theme / "cursors"
    if cursors.exists():
        shutil.rmtree(cursors)
    cursors.mkdir(parents=True, exist_ok=True)
    default_cursors = root / "icons" / "default" / "cursors"
    if default_cursors.exists():
        shutil.rmtree(default_cursors)

    if cursor_src and (cursor_src / "cursors").is_dir():
        for src in sorted((cursor_src / "cursors").iterdir()):
            if src.is_file():
                shutil.copy2(src, cursors / src.name)
        if cursor_license and cursor_license.is_file():
            shutil.copy2(cursor_license, icon_theme / "LICENSE.DMZ-White.txt")
        else:
            write_text(
                icon_theme / "LICENSE.DMZ-White.txt",
                "DMZ-White cursor files are libre cursor theme assets. Install "
                "dmz-cursor-theme documentation for full upstream license text.\n",
            )

    write_text(icon_theme / "cursor.theme", "[Icon Theme]\nInherits=Epin\n")
    write_text(root / "cursors" / "Epin" / "cursor.theme", "[Icon Theme]\nInherits=Epin\n")


def stage_backgrounds(root: Path) -> None:
    backgrounds = root / "backgrounds" / "epin"
    if backgrounds.exists():
        shutil.rmtree(backgrounds)
    backgrounds.mkdir(parents=True, exist_ok=True)
    write_text(backgrounds / "LICENSE.txt", GENERATED_LICENSE)
    write_text(
        backgrounds / "wall0.svg",
        """<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#102033"/>
      <stop offset="0.52" stop-color="#0F766E"/>
      <stop offset="1" stop-color="#7C3AED"/>
    </linearGradient>
  </defs>
  <rect width="1920" height="1080" fill="url(#g)"/>
  <path d="M0 812c300-120 560-92 824-12 302 92 610 160 1096-20v300H0z" fill="#E2E8F0" opacity="0.16"/>
  <path d="M0 920c352-76 570-34 860 8 326 48 646 56 1060-118v270H0z" fill="#0F172A" opacity="0.24"/>
</svg>
""",
    )

    hypr = root / "hypr"
    hypr.mkdir(parents=True, exist_ok=True)
    for idx in range(3):
        src = hypr / f"wall{idx}.png"
        if not src.exists():
            write_png(src, 320, 200, idx)
        if idx == 0:
            shutil.copy2(src, backgrounds / "wall0.png")


def stage_themes(root: Path) -> None:
    theme = root / "themes" / "Epin"
    if theme.exists():
        shutil.rmtree(theme)
    write_text(theme / "LICENSE.txt", GENERATED_LICENSE)
    write_text(
        theme / "index.theme",
        """[Desktop Entry]
Name=Epin
Type=X-GNOME-Metatheme
Comment=Generated Epin desktop theme

[X-GNOME-Metatheme]
GtkTheme=Epin
IconTheme=Epin
CursorTheme=Epin
ButtonLayout=close,minimize,maximize:
""",
    )
    settings = """[Settings]
gtk-theme-name=Epin
gtk-icon-theme-name=Epin
gtk-cursor-theme-name=Epin
gtk-font-name=Noto Sans 10
gtk-xft-antialias=1
gtk-xft-hinting=1
gtk-xft-hintstyle=hintslight
gtk-application-prefer-dark-theme=0
"""
    write_text(theme / "gtk-3.0" / "settings.ini", settings)
    write_text(theme / "gtk-4.0" / "settings.ini", settings)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("asset_root", type=Path)
    parser.add_argument("--cursor-src", type=Path)
    parser.add_argument("--cursor-license", type=Path)
    args = parser.parse_args()

    root = args.asset_root
    root.mkdir(parents=True, exist_ok=True)
    stage_icons(root)
    stage_cursors(root, args.cursor_src, args.cursor_license)
    stage_backgrounds(root)
    stage_themes(root)
    write_text(root / "hos" / "assets" / "README.txt", GENERATED_LICENSE)
    print(f"stage-gui-assets: staged generated GUI assets under {root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
