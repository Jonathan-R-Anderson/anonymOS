// drawText renders s at (x,y) top-left, each source pixel a `scale`-sized block,
// additively at amplitude amp. Unknown runes render as a space.
func drawText(c *canvas, s string, x, y, scale float64, col RGB, amp float64) {
	const cw = 5 // glyph columns
	advance := (cw + 1) * scale
	for _, ch := range s {
		g, ok := glyphs[ch]
		if !ok {
			x += advance
			continue
		}
		for row := 0; row < 7; row++ {
			for cxi := 0; cxi < cw; cxi++ {
				if g[row][cxi] != '#' {
					continue
				}
				px0 := x + float64(cxi)*scale
				py0 := y + float64(row)*scale
				for sy := 0; sy < int(scale+0.999); sy++ {
					for sx := 0; sx < int(scale+0.999); sx++ {
						c.add(int(px0)+sx, int(py0)+sy, col, amp)
					}
				}
			}
		}
		x += advance
	}
}
